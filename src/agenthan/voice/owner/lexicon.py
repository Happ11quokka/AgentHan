"""사장님 언어 정적 사전 (4단계 티켓 03). 런타임 번역 대신 사람이 확인한 값을 쓴다.

- `options`: 옵션 이름(한국어, `MenuOption.name`) → 사장님 언어. 계약에 옵션 원어 이름 칸이 없어서
  (계약 제안 9, 제안만) Part C가 들고 있다. 지금 더미 가게 옵션 4개.
  사전에 없는 옵션은 한국어 그대로
- `terms`: 손님 요청 속 재료 낱말 중 Papago ko→ru가 뜻을 자주 틀리는 것(동음이의어). 번역 전에
  자리표시자로 바꾸고 번역 뒤 이 값으로 넣는다. 2026-11-10 개인 키로 잰 오역:
  고수 → "мастер"·"корица"(명인·계피), 파는 → "Продам"(판다), 초 → "секундочку"(1초),
  밤 → "ночь"(밤 시간). 견과류·땅콩·마늘·양파·깨는 바로 맞게 나와 넣지 않는다
  (자리표시자로 바꾸면 "없이" 같은 부정이 오히려 흐려졌다: "[1] 없이" → "без меня")
- `numerals`: 번역문 숫자 확인에서 원문 숫자 대신 나와도 되는 낱말(Papago가 "2개"를 "два"로 푼다)

러시아어는 격 변화가 있어 자리표시자 자리에 넣은 낱말이 주격 그대로다("Уберите кинза").
뜻은 맞고, 한국어 원문과 배지가 함께 보인다.
"""

from __future__ import annotations

from dataclasses import dataclass, field


@dataclass(frozen=True)
class Lexicon:
    lang: str
    options: dict[str, str] = field(default_factory=dict)
    terms: dict[str, str] = field(default_factory=dict)
    numerals: dict[int, tuple[str, ...]] = field(default_factory=dict)

    def option(self, name_ko: str) -> str:
        """옵션 이름을 사장님 언어로. 사전에 없으면 한국어 그대로."""
        return self.options.get(name_ko, name_ko)


RU = Lexicon(
    lang="ru",
    options={
        "홀케이크 변경": "Целый торт",
        "디카페인 변경": "Без кофеина",
        "샷 추가": "Доп. шот эспрессо",
        "사워크림 빼기": "Без сметаны",
    },
    terms={
        "고수": "кинза",
        "파": "зелёный лук",
        "초": "свечи",
        "밤": "каштаны",
    },
    numerals={
        1: ("один", "одна", "одну", "одно", "одного", "одной"),
        2: ("два", "две", "двух", "двум", "двумя"),
        3: ("три", "трёх", "трех", "трём", "трем", "тремя"),
        4: ("четыре", "четырёх", "четырех", "четырьмя"),
        5: ("пять", "пяти", "пятью"),
        6: ("шесть", "шести"),
        7: ("семь", "семи"),
        8: ("восемь", "восьми"),
        9: ("девять", "девяти"),
        10: ("десять", "десяти"),
    },
)

# 사장님 언어 → 사전. 데모 언어는 ru 하나(spec "번역")
LEXICONS = {"ru": RU}


def lexicon_for(lang: str) -> Lexicon:
    """없는 언어면 빈 사전(옵션은 한국어, 보호 낱말 없음)."""
    return LEXICONS.get(lang) or Lexicon(lang=lang)
