"""TTS로 보내기 전 숫자를 말로 (5단계 티켓 10). 자막은 숫자 그대로, 소리만 말로."""

from __future__ import annotations

import pytest

from agenthan.voice.tts_text import sino, to_spoken


@pytest.mark.parametrize(("n", "said"), [
    (0, "영"), (5, "오"), (10, "십"), (15, "십오"), (20, "이십"), (100, "백"), (500, "오백"),
    (1_000, "천"), (4_500, "사천오백"), (9_000, "구천"), (10_000, "만"), (19_500, "만 구천오백"),
    (38_000, "삼만 팔천"), (52_500, "오만 이천오백"), (120_000, "십이만"), (1_004_000, "백만 사천"),
])
def test_sino_numbers(n: int, said: str) -> None:
    assert sino(n) == said


@pytest.mark.parametrize(("text", "said"), [
    ("총 19,500원이에요.", "총 만 구천오백 원이에요."),
    ("38,000원 더 받아요.", "삼만 팔천 원 더 받아요."),
    ("6시 반에 찾으러 오시고", "여섯 시 반에 찾으러 오시고"),
    ("4시 20분까지 해 둘게요.", "네 시 이십 분까지 해 둘게요."),
    ("오후 8시에 오시는 거죠?", "오후 여덟 시에 오시는 거죠?"),
    ("12시 5분", "열두 시 오 분"),
    ("준비하는 데 15분쯤 걸려요.", "준비하는 데 십오 분쯤 걸려요."),
    ("한 번에 10개까지", "한 번에 열 개까지"),
    ("메도빅 두 개랑 아이스 아메리카노 한 잔이요.", "메도빅 두 개랑 아이스 아메리카노 한 잔이요."),
])
def test_to_spoken(text: str, said: str) -> None:
    assert to_spoken(text) == said
